import AppKit
import ApplicationServices
import Carbon

/// How accepted text reaches the host app, chosen per app by the compatibility database.
enum InsertionStrategy: String {
    /// Synthetic Unicode keystrokes (default): the host sees ordinary typing.
    case keystrokes
    /// Clipboard + Cmd-V, then the previous clipboard is restored.
    case paste
    /// Keystrokes for short text, paste for long text (Cotypist's default behaviour).
    case pasteLong = "paste-long"
    /// Type the first word, paste the rest (apps that drop the first pasted character).
    case firstWordThenPaste = "first-word-then-paste"
}

/// Types accepted text into the focused app.
///
/// Keystrokes follow espanso and Tabber: at most 20 UTF-16 units per event, virtual key 0
/// (pages read 49/52 as Space/Enter and Chrome drops unassigned codes), real Return for
/// newlines, and posting at the annotated session tap so session taps (ours included) skip
/// the events. Every event carries `marker` in its user data.
///
/// Paste borrows the general pasteboard, marks the temporary item as transient so clipboard
/// managers skip it, and restores the user's clipboard afterwards. Since macOS 15.4 reading
/// the pasteboard can raise a permission alert, so paste is used only when access is
/// "always allow"; otherwise insertion falls back to keystrokes rather than lose the
/// user's clipboard.
enum Inserter {
    static let marker: Int64 = 0x4654_5950 // "FTYP"
    /// Length from which `paste-long` switches to the clipboard.
    static let longText = 40

    private static let source: CGEventSource? = {
        let s = CGEventSource(stateID: .privateState)
        s?.userData = marker
        return s
    }()

    private static func post(key: CGKeyCode, flags: CGEventFlags = [], unicode: [UniChar]? = nil) {
        for down in [true, false] {
            guard let ev = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down) else { continue }
            ev.flags = flags
            if var u = unicode {
                ev.keyboardSetUnicodeString(stringLength: u.count, unicodeString: &u)
            }
            ev.setIntegerValueField(.eventSourceUserData, value: marker)
            ev.post(tap: .cgAnnotatedSessionEventTap)
        }
    }

    static func insert(_ text: String, strategy: InsertionStrategy) {
        switch strategy {
        case .keystrokes:
            type(text)
        case .paste:
            if !paste(text) { type(text) }
        case .pasteLong:
            if text.count < longText || !paste(text) { type(text) }
        case .firstWordThenPaste:
            let lead = text.prefix { $0 == " " }
            let word = text.dropFirst(lead.count).prefix { !$0.isWhitespace }
            let head = String(lead + word)
            let rest = String(text.dropFirst(head.count))
            type(head)
            if !rest.isEmpty, !paste(rest) { type(rest) }
        }
    }

    static func type(_ text: String) {
        var chunk: [UniChar] = []
        func flush() {
            if !chunk.isEmpty { post(key: 0, unicode: chunk) }
            chunk.removeAll()
        }
        for ch in text {
            if ch == "\n" || ch == "\r\n" {
                flush()
                post(key: 36)
                continue
            }
            let units = Array(String(ch).utf16)
            if chunk.count + units.count > 20 { flush() }
            chunk.append(contentsOf: units)
        }
        flush()
    }

    /// Deletes `count` characters before the caret (Backspace, one per character).
    static func deleteBackward(_ count: Int) {
        for _ in 0..<count { post(key: 51) }
    }

    /// Re-sends a plain key press (used to give back a key the tap swallowed).
    static func press(key: CGKeyCode) {
        post(key: key)
    }

    // MARK: - Paste

    /// True when the clipboard can be read (and so restored) without a permission alert.
    static var canRestoreClipboard: Bool {
        if #available(macOS 15.4, *) {
            return NSPasteboard.general.accessBehavior == .alwaysAllow
        }
        return true
    }

    /// Pasteboard types that tell clipboard managers to ignore an item
    /// (nspasteboard.org conventions).
    private static let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.source"),
    ]

    /// Pastes `text` and restores the clipboard. Returns false (having done nothing) when the
    /// clipboard could not be restored afterwards.
    @discardableResult
    static func paste(_ text: String) -> Bool {
        guard canRestoreClipboard else {
            Log.debug("paste skipped: clipboard access is not 'always allow'; typing instead")
            return false
        }
        let pb = NSPasteboard.general
        let saved: [[NSPasteboard.PasteboardType: Data]] = (pb.pasteboardItems ?? []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let data = item.data(forType: t) { d[t] = data } }
            return d
        }
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for t in transientTypes { item.setString(t.rawValue == "org.nspasteboard.source" ? "dev.foretype.Foretype" : "", forType: t) }
        pb.writeObjects([item])
        let ours = pb.changeCount

        post(key: vKeyCode, flags: .maskCommand)

        // The host reads the pasteboard asynchronously; give it time before restoring, and
        // leave the clipboard alone if the user copied something in the meantime.
        DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(250)) {
            guard pb.changeCount == ours else { return }
            pb.clearContents()
            if !saved.isEmpty {
                let items = saved.map { d -> NSPasteboardItem in
                    let it = NSPasteboardItem()
                    for (t, data) in d { it.setData(data, forType: t) }
                    return it
                }
                pb.writeObjects(items)
            }
        }
        return true
    }

    /// Key code that types "v" in the current keyboard layout (Cmd-V must follow the layout,
    /// e.g. Dvorak), falling back to the ANSI position.
    private static var vKeyCode: CGKeyCode {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let ptr = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return 9 }
        let data = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        return data.withUnsafeBytes { raw -> CGKeyCode in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return 9 }
            for code in 0..<UInt16(128) {
                var dead: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var len = 0
                let err = UCKeyTranslate(layout, code, UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()),
                                         OptionBits(kUCKeyTranslateNoDeadKeysBit), &dead, 4, &len, &chars)
                if err == noErr, len == 1, chars[0] == UniChar(("v" as Unicode.Scalar).value) { return code }
            }
            return 9
        }
    }
}
